const here = path.dirname(fileURLToPath(import.meta.url))
const repoRoot = path.resolve(here, '..', '..')
const moduleRoot = process.env.SWEET_HAND_MODULE_ROOT ?? path.join(repoRoot, 'frontend')

const require = createRequire(pathToFileURL(path.join(moduleRoot, 'package.json')))
const { chromium } = require('@playwright/test')

const SITE_URL = 'https://sweethand.ca'
const FLYER_PDF = 'sweet-hand-pre-launch-flyer.pdf'
const FLYER_TRIM = { w: 5, h: 7 }
const FLYER_BLEED = 0.125
const STICKERS = [
  { slug: 'sticker-1-wordmark', title: 'Sweet Hand wordmark badge' },
  { slug: 'sticker-2-sweet-hand', title: 'You have a sweet hand' },
  { slug: 'sticker-3-dish-ring', title: 'Sweet Hand dish ring' },
]

const inches = (px) => (px / 300).toFixed(2)

const GROUPS = ['flyer', 'stickers', 'whatsapp', 'youtube', 'facebook']
const onlyFlag = process.argv.indexOf('--only')
const only = onlyFlag === -1 ? GROUPS : process.argv.slice(onlyFlag + 1).filter((g) => !g.startsWith('--'))
for (const g of only) {
  if (!GROUPS.includes(g)) throw new Error(`--only: unknown group "${g}" (expected ${GROUPS.join(', ')})`)
}
const wants = (group) => only.includes(group)

/** PNG header reader: enough to assert dimensions and pixel format. */
function readPngHeader(buffer) {
  return {
    width: buffer.readUInt32BE(16),
    height: buffer.readUInt32BE(20),
    colourType: buffer.readUInt8(25), // 6 = truecolour with alpha
  }
}

/** A QR for SITE_URL as an SVG: one path, 4-module quiet zone, white background. */
async function writeQr() {
  const qr = qrcodegen.QrCode.encodeText(SITE_URL, qrcodegen.QrCode.Ecc.MEDIUM)
  const quiet = 4
  const size = qr.size + quiet * 2
  const cells = []
  for (let y = 0; y < qr.size; y += 1) {
    for (let x = 0; x < qr.size; x += 1) {
      if (qr.getModule(x, y)) cells.push(`M${x + quiet},${y + quiet}h1v1h-1z`)
    }
  }
  const svg = `<?xml version="1.0" encoding="UTF-8"?>
<!-- QR code for ${SITE_URL}. Generated by docs/marketing/render.mjs; do not edit. -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${size} ${size}" shape-rendering="crispEdges">
  <title>QR code for sweethand.ca</title>
  <rect width="${size}" height="${size}" fill="#ffffff"/>
  <path d="${cells.join('')}" fill="#141312"/>
</svg>
`
  await writeFile(path.join(here, 'assets', 'qr-sweethand-ca.svg'), svg)
  return { modules: qr.size, version: qr.version }
}

const browser = await chromium.launch({
  args: ['--allow-file-access-from-files', '--font-render-hinting=none'],
})

/** Force the face to load, then hard-fail rather than ship a system fallback. */
async function requireFigtree(page, label) {
  const ok = await page.evaluate(async () => {
    await Promise.all(
      ['500 20px "Figtree"', '700 20px "Figtree"', '800 20px "Figtree"'].map((s) => document.fonts.load(s).catch(() => {})),
    )
    await document.fonts.ready
    return document.fonts.check('700 20px "Figtree"') && [...document.fonts].some((f) => f.family.includes('Figtree') && f.status === 'loaded')
  })
  if (!ok) throw new Error(`${label}: Figtree did not load (system font fallback)`)
}

async function renderFlyer() {
  const src = pathToFileURL(path.join(here, 'flyer', 'flyer.html')).href

  // PDF: page 1 front, page 2 back, page size from the CSS @page rule.
  const pdfCtx = await browser.newContext()
  const pdfPage = await pdfCtx.newPage()
  await pdfPage.goto(src, { waitUntil: 'load' })
  await requireFigtree(pdfPage, 'flyer')
  const pdf = await pdfPage.pdf({ preferCSSPageSize: true, printBackground: true })
  await pdfCtx.close()
  await writeFile(path.join(here, 'flyer', FLYER_PDF), pdf)

  assertPdf('flyer PDF', pdf, { pages: 2, w: 5.25, h: 7.25 })

  // Print-shop versions: crop marks single-up, and 4-up on a 12 x 18 in sheet.
  const press = { src, selector: '.sheet', trim: FLYER_TRIM, bleed: FLYER_BLEED, ready: (p) => requireFigtree(p, 'flyer press') }
  const labels = (layout) => ['front', 'back'].map((side) => `Sweet Hand pre-launch flyer · ${side} · trim 5 × 7 in · bleed 0.125 in · ${layout}`)
  const crop = await pressPdf(browser, { ...press, labels: labels('crop marks') })
  assertPdf('flyer crop marks', crop.pdf, { pages: 2, w: 6, h: 8 })
  await writeFile(path.join(here, 'flyer', FLYER_PDF.replace('.pdf', '-crop-marks.pdf')), crop.pdf)
  const gang = await pressPdf(browser, { ...press, sheet: { w: 12, h: 18 }, cols: 2, rows: 2, labels: labels('4-up, flip on long edge') })
  assertPdf('flyer 4-up', gang.pdf, { pages: 2, w: 12, h: 18 })
  await writeFile(path.join(here, 'flyer', FLYER_PDF.replace('.pdf', '-4up-12x18.pdf')), gang.pdf)

  // Proofs: 5.25 x 7.25 in at 300 dpi = 1575 x 2175, no guides.
  const ctx = await browser.newContext({
    viewport: { width: 640, height: 760 },
    deviceScaleFactor: 300 / 96,
  })
  const page = await ctx.newPage()
  await page.goto(src, { waitUntil: 'load' })
  await page.evaluate(() => document.body.classList.add('proof'))
  await requireFigtree(page, 'flyer proof')
  for (const [side, selector] of [['front', '.front'], ['back', '.back']]) {
    const out = path.join(here, 'flyer', `proof-${side}.png`)
    await page.locator(selector).screenshot({ path: out, animations: 'disabled' })
    const { width, height } = readPngHeader(await readFile(out))
    if (width !== 1575 || height !== 2175) throw new Error(`proof-${side}: expected 1575x2175, got ${width}x${height}`)
  }
  await ctx.close()
  console.log(`✓ flyer ${FLYER_PDF} (2 pages, 5.25 x 7.25 in), -crop-marks.pdf, -4up-12x18.pdf, proof-front.png, proof-back.png (1575x2175)`)
}

/** Lifts a sticker's <svg> into a standalone file: font inlined, cut line layer added. */
async function exportSvg(slug, title) {
  const html = await readFile(path.join(here, 'stickers', 'src', `${slug}.html`), 'utf8')
  const css = await readFile(path.join(here, 'stickers', 'src', 'stickers.css'), 'utf8')
  const font = (await readFile(path.join(here, 'assets', 'fonts', 'figtree-latin.woff2'))).toString('base64')
  const fontFace = `@font-face {
  font-family: "Figtree";
  src: url("data:font/woff2;base64,${font}") format("woff2");
  font-weight: 300 900;
  font-style: normal;
}`
  const idioms = css.slice(css.indexOf('/* --- Shared artwork idioms')).trim()

  const svgOpen = html.search(/<svg[\s>]/)
  const svgTagEnd = html.indexOf('>', svgOpen)
  const openTag = html.slice(svgOpen, svgTagEnd + 1).replace(/\sclass="[^"]*"/, '')
  const inner = html.slice(svgTagEnd + 1, html.lastIndexOf('</svg>'))

  // The first <g> is the silhouette; reuse it as the hidden magenta cut line.
  const gStart = inner.indexOf('<g>')
  const gEnd = inner.indexOf('</g>', gStart) + 4
  const cutline = inner
    .slice(gStart, gEnd)
    .replace(/class="keyline"/g, 'class="cutline-path"')
    .replace(/\sstyle="--art-stroke:[^"]*"/g, '')
    .replace('<g>', '<g id="cutline">')

  const style = `<style>
${fontFace}

${idioms}

#cutline { display: none; }
.cutline-path { fill: none; stroke: #ff00ff; stroke-width: 2; stroke-linejoin: round; }
</style>`
  const body = inner.replace(/(<title>[^<]*<\/title>)/, `$1\n    ${style.replace(/\n/g, '\n    ')}`)

  const svg = `<?xml version="1.0" encoding="UTF-8"?>
<!--
  Sweet Hand die-cut sticker — ${title}
  Generated by docs/marketing/render.mjs from stickers/src/${slug}.html.
  Edit the HTML, not this file.

  The die cut is the outer edge of the white keyline, which is also the alpha
  edge of ${slug}.png. #cutline traces the *artwork* outline in magenta (the
  prepress convention) and is hidden by default; the actual cut runs 65px
  (0.217in at 300 DPI) outside it.
  Text is live — outline it before sending this SVG to a printer that is not
  rasterising the PNG.
-->
${openTag.replace('<svg', '<svg width="3in" height="3in"')}${body.trimEnd()}
  ${cutline}
</svg>
`
  await writeFile(path.join(here, 'stickers', `${slug}.svg`), svg)
}

async function renderSticker(slug, { preview }) {
  const ctx = await browser.newContext({ viewport: { width: 1000, height: 1000 }, deviceScaleFactor: 1, reducedMotion: 'reduce' })
  const page = await ctx.newPage()
  await page.goto(pathToFileURL(path.join(here, 'stickers', 'src', `${slug}.html`)).href, { waitUntil: 'load' })
  if (preview) await page.evaluate(() => document.body.classList.add('preview'))
  await requireFigtree(page, slug)
  const out = path.join(here, 'stickers', preview ? `${slug}-preview.png` : `${slug}.png`)
  await page.locator('.stage').screenshot({ path: out, omitBackground: !preview, animations: 'disabled' })
  await ctx.close()
  return out
}

/** Alpha bounding box (the die cut), corner alpha, and how many separate opaque pieces there are. */
async function measureAlpha(pngPath) {
  const ctx = await browser.newContext()
  const page = await ctx.newPage()
  const uri = `data:image/png;base64,${(await readFile(pngPath)).toString('base64')}`
  const result = await page.evaluate(async (u) => {
    const img = new Image()
    img.src = u
    await img.decode()
    const { width: w, height: h } = img
    const canvas = document.createElement('canvas')
    canvas.width = w
    canvas.height = h
    const c = canvas.getContext('2d', { willReadFrequently: true })
    c.drawImage(img, 0, 0)
    const { data } = c.getImageData(0, 0, w, h)
    const solid = (i) => data[i * 4 + 3] > 8
    let minX = w, minY = h, maxX = -1, maxY = -1
    for (let y = 0; y < h; y += 1) {
      for (let x = 0; x < w; x += 1) {
        if (solid(y * w + x)) {
          if (x < minX) minX = x
          if (x > maxX) maxX = x
          if (y < minY) minY = y
          if (y > maxY) maxY = y
        }
      }
    }
    // Connected components (4-neighbour) of opaque pixels: a die cut must be one piece.
    const seen = new Uint8Array(w * h)
    let pieces = 0
    const stack = []
    for (let start = 0; start < w * h; start += 1) {
      if (seen[start] || !solid(start)) continue
      pieces += 1
      stack.push(start)
      seen[start] = 1
      while (stack.length) {
        const p = stack.pop()
        const x = p % w
        const y = (p - x) / w
        for (const q of [x > 0 ? p - 1 : -1, x < w - 1 ? p + 1 : -1, y > 0 ? p - w : -1, y < h - 1 ? p + w : -1]) {
          if (q >= 0 && !seen[q] && solid(q)) {
            seen[q] = 1
            stack.push(q)
          }
        }
      }
    }
    const a = (x, y) => data[(y * w + x) * 4 + 3]
    return { minX, minY, maxX, maxY, pieces, corners: [a(0, 0), a(w - 1, 0), a(0, h - 1), a(w - 1, h - 1)] }
  }, uri)
  await ctx.close()
  return result
}

async function renderStickers() {
  for (const { slug, title } of STICKERS) {
    const printPath = await renderSticker(slug, { preview: false })
    await renderSticker(slug, { preview: true })

    const { width, height, colourType } = readPngHeader(await readFile(printPath))
    if (width !== 900 || height !== 900) throw new Error(`${slug}: expected 900x900, got ${width}x${height}`)
    if (colourType !== 6) throw new Error(`${slug}: expected RGBA (colour type 6), got ${colourType}`)

    const { minX, minY, maxX, maxY, pieces, corners } = await measureAlpha(printPath)
    if (corners.some((a) => a !== 0)) throw new Error(`${slug}: corners are not transparent (${corners.join(',')})`)
    if (minX < 2 || minY < 2 || maxX > width - 3 || maxY > height - 3) {
      throw new Error(`${slug}: artwork touches the canvas edge (x ${minX}-${maxX}, y ${minY}-${maxY}); the die cut would be clipped`)
    }
    if (pieces !== 1) throw new Error(`${slug}: die cut is ${pieces} separate pieces, expected 1`)

    await exportSvg(slug, title)
    const artW = maxX - minX + 1
    const artH = maxY - minY + 1
    console.log(
      `✓ ${title.padEnd(26)} ${path.basename(printPath).padEnd(28)} cut ${artW}x${artH}px (${inches(artW)}" x ${inches(artH)}")  margins L${minX} R${width - 1 - maxX} T${minY} B${height - 1 - maxY}`,
    )
  }

  const ctx = await browser.newContext({ viewport: { width: 1500, height: 560 } })
  const page = await ctx.newPage()
  const tiles = (
    await Promise.all(
      STICKERS.map(async ({ slug, title }) => {
        const data = (await readFile(path.join(here, 'stickers', `${slug}.png`))).toString('base64')
        return `<figure><img src="data:image/png;base64,${data}" width="440"><figcaption>${title}</figcaption></figure>`
      }),
    )
  ).join('')
  await page.setContent(
    `<body style="margin:0;padding:40px;background:#f1eee9;display:flex;gap:40px;align-items:flex-start;font:600 16px system-ui;color:#141312">
       <style>figure{margin:0;text-align:center}figcaption{margin-top:14px}img{display:block}</style>${tiles}</body>`,
  )
  await page.waitForTimeout(300)
  await page.locator('body').screenshot({ path: path.join(here, 'stickers', 'contact-sheet.png') })
  await ctx.close()
  console.log('✓ contact sheet               contact-sheet.png')
}

